from app.seeds.jobs_sewing_catalog import build_sewing_jobs_catalog


def _opts(*labels: str) -> list[dict[str, str]]:
    return [{"value": label, "label": label} for label in labels]


def _group(label: str, options: tuple[str, ...]) -> dict[str, Any]:
    return {"label": label, "options": _opts(*options)}


def _experience() -> dict[str, Any]:
    return _group("Опыт", ("Без опыта", "До 3 лет", "Более 3 лет"))


def _section(
    slug: str,
    label: str,
    roles: tuple[str, ...],
    filters: list[dict[str, Any]],
    question: str = "Какая вакансия?",
) -> dict[str, Any]:
    return {
        "category_slug": slug,
        "label": label,
        "question": question,
        "roles": _opts(*roles),
        "filters": filters,
    }


def _sewing_section() -> dict[str, Any]:
    catalog = build_sewing_jobs_catalog()
    catalog["question"] = "Какая вакансия?"
    return catalog


