def _opts(*labels: str) -> list[dict[str, str]]:
    return [{"value": label, "label": label} for label in labels]


def _group(
    label: str,
    options: tuple[str, ...],
    kinds: tuple[str, ...] | None = None,
) -> dict[str, Any]:
    group: dict[str, Any] = {"label": label, "options": _opts(*options)}
    if kinds:
        group["applies_to"] = list(kinds)
    return group


def _seller() -> dict[str, Any]:
    return _group("Продавец", ("Частное лицо", "Магазин", "Другой"))


def _condition() -> dict[str, Any]:
    return _group("Состояние", ("Новое", "Б/у"))


def _section(
    slug: str,
    label: str,
    kinds: tuple[str, ...],
    filters: list[dict[str, Any]],
    question: str = "Какой товар?",
) -> dict[str, Any]:
    return {
        "category_slug": slug,
        "label": label,
        "question": question,
        "roles": _opts(*kinds),
        "filters": filters,
    }


