"""Вакансии швейного производства.

Это работа, не услуга пошива. Вид — должность, а не изделие и не тип машинки.
Бухгалтерия, охрана, транспорт и общее производство — другие разделы Работы.
"""
from __future__ import annotations

from typing import Any


def _opts(*labels: str) -> list[dict[str, str]]:
    return [{"value": label, "label": label} for label in labels]


def _group(label: str, options: tuple[str, ...]) -> dict[str, Any]:
    return {"label": label, "options": _opts(*options)}


